/** The group a token belongs to: the first path segment, which is the component name in `comp`. */
export function groupOf(token: ManifestToken): string {
  const segments = token.path.split('.');
  return (token.tier === 'sys' ? segments[0] : segments[1]) ?? token.tier;
}

/** A colour a row can print: the colorset the OS resolves, and the token it was reached through. */
interface ColorSource {
  /** The colorset's asset name, or null when nothing in the chain has one. */
  readonly asset: string | null;
  /** The public path of the system token a `comp` token aliases, or null when this token *is* the colorset. */
  readonly alias: string | null;
}

/**
 * The system token each `comp` token is a whole-value alias of, by token id.
 *
 * A `comp` colour has no colorset of its own — the component tier is *one whole-value alias of a
 * system token per component part* (ARCHITECTURE §5) — so `manifest.json` carries no `asset` for one
 * and the app had nothing to print but the words "aliased colorset" beside a swatch that was right.
 * The reference is in the tier's own documents (`"$value": "{sys.color.border.strong}"`), so the
 * generator reads it here with the same two readers the token pipeline uses, and a row prints the
 * target's value and names the target.
 *
 * Brands override `ref` only (`BRAND_OVERRIDABLE`, ADR-0020 §1), so an alias is the same for every
 * brand and can be resolved once, at generation time.
 */
export function compAliases(reader: SourceReader, problems: string[]): Map<string, string> {
  const out = new Map<string, string>();
  for (const entry of reader.list(COMP_TOKENS_DIR)) {
    if (entry.dir || !entry.name.endsWith('.tokens.json')) continue;
    const file = posix.join(COMP_TOKENS_DIR, entry.name);
    let tree: unknown;
    try {
      tree = JSON.parse(reader.readText(file));
    } catch {
      problems.push(`${file}: is not readable as JSON`);
      continue;
    }
    if (!isRecord(tree)) {
      problems.push(`${file}: is not a DTCG document`);
      continue;
    }
    for (const [id, node] of collectTokens(tree)) {
      const target = aliasTarget(node['$value']);
      if (target !== null) out.set(id.replace(/\.\$root$/, ''), target);
    }
  }
  return out;
}

/** A token id as the manifest writes ids, and as it writes public paths (`sys.` is not in a path). */
function manifestKeys(byId: Map<string, ManifestToken>, byPath: Map<string, ManifestToken>, id: string): ManifestToken | null {
  return byId.get(id) ?? byId.get(`${id}.$root`) ?? byPath.get(id.replace(/^sys\./, '')) ?? null;
}

/**
 * Where a colour token's painted value comes from: its own colorset, or the one it aliases, following
 * the chain a `comp` token may take through another `comp` token. An unresolvable chain is reported,
 * never guessed — the app would otherwise print a swatch beside a value that is not in it.
 */
function colorSource(
  token: ManifestToken,
  aliases: ReadonlyMap<string, string>,
  byId: Map<string, ManifestToken>,
  byPath: Map<string, ManifestToken>,
  problems: string[],
): ColorSource {
  if (token.asset !== null) return { asset: token.asset, alias: null };
  const seen = new Set<string>([token.id]);
  let current: ManifestToken = token;
  // Four hops is more than the tier allows; it is here so a cycle in the sources cannot hang a build.
  for (let hop = 0; hop < 4; hop += 1) {
    const target = aliases.get(current.id);
    if (target === undefined) break;
    const next = manifestKeys(byId, byPath, target);
    if (next === null) {
      problems.push(`${token.path}: aliases ${target}, which is not a token of the manifest`);
      return { asset: null, alias: null };
    }
    if (seen.has(next.id)) {
      problems.push(`${token.path}: its alias chain returns to ${next.path}`);
      return { asset: null, alias: null };
    }
    seen.add(next.id);
    if (next.asset !== null) return { asset: next.asset, alias: next.path };
    current = next;
  }
  problems.push(`${token.path}: no colorset behind it — nothing in its alias chain carries one`);
  return { asset: null, alias: null };
}

/** The Swift value expression for a member, or null when the type table does not know the member. */
function valueExpression(token: ManifestToken, table: TypeTable, colors: (t: ManifestToken) => ColorSource): string | null {
  const member = token.swift;
  if (member === null) return '.unavailable';

  const faces = /^DSBrand\.faces\[\.([A-Za-z]+)\]$/.exec(member);
  if (faces !== null) return `.fontFace(.${faces[1] ?? ''})`;

  const parts = member.split('.');
  const root = parts[0] ?? '';
  const chain = parts.slice(1);
  if (chain.length === 0) return null;

  // `DSColor.accent` is `DSTokenSet.color.accent`: the brand's colors hang off the token set.
  const keyPathChain = root === 'DSColor' ? ['color', ...chain] : chain;
  const lookup = memberType(table, root === 'DSColor' ? 'DSColor' : 'DSTokenSet', chain);
  if (lookup === null) return null;
  const keyPath = `\\.${keyPathChain.join('.')}`;

  switch (lookup.type) {
    case 'CGFloat':
      return `.dimension(${keyPath})`;
    case 'Double':
      return `.number(${keyPath})`;
    case 'TimeInterval':
      return `.duration(${keyPath})`;
    case 'Bool':
      return `.flag(${keyPath})`;
    case 'Color': {
      const source = colors(token);
      const asset = source.asset === null ? 'nil' : `DSColorToken(rawValue: ${swiftString(source.asset)})`;
      return `.color(${keyPath}, ${asset}, ${optionalString(source.alias)})`;
    }
    case 'DSTypeRole': {
      // A type role is rendered with `dsText(_:)`, which takes a key path into `DSTokenSet.Typography`.
      const inner = keyPathChain.slice(1).join('.');
      return keyPathChain[0] === 'typography' ? `.typography(\\.${inner})` : null;
    }
    case 'DSShadowToken':
      return `.shadow(${keyPath})`;
    case 'DSGradientToken':
      return `.gradient(${keyPath})`;
    case 'DSSpringToken':
      return `.spring(${keyPath})`;
    case 'DSCubicBezier':
      return `.easing(${keyPath})`;
    case 'DSStrokeStyle':
      return `.stroke(${keyPath})`;
    default:
      return null;
  }
}

/** A Swift identifier for a group's array: `sysColor`, `refBlur`, `compAreaChart`. */
function groupSymbol(tier: string, group: string): string {
  const words = group.split(/[-.]/).filter((w) => w !== '');
  const camel = words.map((w, i) => (i === 0 ? w : w.charAt(0).toUpperCase() + w.slice(1))).join('');
  return `${tier}${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
}

function optionalString(value: string | null): string {
  return value === null || value === '' ? 'nil' : swiftString(value);
}

export function renderTokenCatalog(reader: SourceReader, problems: string[]): OutputFile {
  const manifest = JSON.parse(reader.readText(TOKEN_MANIFEST)) as { tokens: ManifestToken[] };
  const table = readTypeTable(reader);
  const version = reader.readText(VERSION_FILE).trim();
  const byId = new Map(manifest.tokens.map((t) => [t.id, t] as const));
  const byPath = new Map(manifest.tokens.map((t) => [t.path, t] as const));
  const aliases = compAliases(reader, problems);
  const colors = (token: ManifestToken): ColorSource => colorSource(token, aliases, byId, byPath, problems);

  const byGroup = new Map<string, ManifestToken[]>();
  for (const token of manifest.tokens) {
    const key = `${token.tier}\u0000${groupOf(token)}`;
    const list = byGroup.get(key);
    if (list === undefined) byGroup.set(key, [token]);
    else list.push(token);
  }

  // Sections, biggest first inside a tier: the app's Foundations order is the data's own shape.
  const order = ['sys', 'comp', 'ref'];
  const groups = [...byGroup.entries()]
    .map(([key, tokens]) => {
      const [tier = '', group = ''] = key.split('\u0000');
      return { tier, group, tokens };
    })
    .sort((a, b) =>
      order.indexOf(a.tier) - order.indexOf(b.tier) ||
      b.tokens.length - a.tokens.length ||
      (a.group < b.group ? -1 : a.group > b.group ? 1 : 0),
    );

  const lines: string[] = [
    header(`${TOKEN_MANIFEST} and swift/Sources/DSTokens/Generated`),
    '//',
    '// One entry per token of the manifest. `value` carries a KeyPath into `DSTokenSet`, so the app shows the',
    '// value the running scene resolves and never a literal; a `ref` primitive has no Swift API and says so.',
    'import SwiftUI',
    'import DSTokens',
    '',
    'extension DSTokenCatalog {',
    `    /// The system version the tokens were built at (\`VERSION\`).`,
    `    public static let version = ${swiftString(version)}`,
    '',
  ];

  for (const { tier, group, tokens } of groups) {
    const symbol = groupSymbol(tier, group);
    lines.push(`    static let ${symbol}: [DSTokenCatalogEntry] = [`);
    for (const token of tokens) {
      const value = valueExpression(token, table, colors);
      if (value === null) {
        problems.push(`${token.path}: no Swift member type for ${token.swift ?? '(none)'} — the token catalogue is stale`);
        continue;
      }
      const css = token.css ?? token.cssVars[0] ?? null;
      lines.push(
        `        DSTokenCatalogEntry(` +
          `path: ${swiftString(token.path)}, ` +
          `id: ${swiftString(token.id)}, ` +
          `tier: .${tier}, ` +
          `group: ${swiftString(group)}, ` +
          `type: ${swiftString(token.type)}, ` +
          `swiftMember: ${optionalString(token.swift)}, ` +
          `cssVariable: ${optionalString(css)}, ` +
          `summary: ${optionalString(token.description)}, ` +
          `deprecated: ${optionalString(token.deprecated)}, ` +
          `value: ${value}),`,
      );
    }
    lines.push('    ]', '');
  }

  lines.push('    /// Every group, in the order the Foundations screen lists them.');
  lines.push('    public static let groups: [DSTokenGroup] = [');
  for (const { tier, group, tokens } of groups) {
    lines.push(
      `        DSTokenGroup(tier: .${tier}, name: ${swiftString(group)}, count: ${tokens.length}, entries: ${groupSymbol(tier, group)}),`,
    );
  }
  lines.push('    ]', '}');
  return { path: posix.join(GENERATED_ROOT, 'DSTokenCatalog.swift'), contents: file(lines) };
}

