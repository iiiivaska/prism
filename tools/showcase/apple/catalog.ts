function header(sources: string): string {
  return `// Generated by tools/showcase/apple from ${sources}. Do not edit; run ${BUILD_COMMAND}.`;
}

function file(lines: readonly string[]): string {
  return `${lines.join('\n').replace(/[ \t]+$/gm, '')}\n`;
}

