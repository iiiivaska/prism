interface SpecExample {
  readonly id: string;
  readonly props: readonly (readonly [string, unknown])[];
  readonly surface: string | null;
  readonly backdrop: string | null;
  readonly grid: readonly string[];
  readonly schemes: readonly string[];
  readonly description: string | null;
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

function propValue(value: unknown): string {
  if (typeof value === 'string') return `.string(${swiftString(value)})`;
  if (typeof value === 'number') return `.number(${Number.isInteger(value) ? `${value}` : `${value}`})`;
  if (typeof value === 'boolean') return `.bool(${value ? 'true' : 'false'})`;
  if (Array.isArray(value)) return `.list([${value.map(propValue).join(', ')}])`;
  if (isRecord(value)) {
    const pairs = Object.entries(value).map(([k, v]) => `DSPropValue.Pair(${swiftString(k)}, ${propValue(v)})`);
    return `.map([${pairs.join(', ')}])`;
  }
  return '.unknown';
}

/** The spec's props of `type: action`, which a harness must stage with a handler (see `actionsOf`). */
function actionPropsOf(spec: SpecRow): string[] {
  const raw = spec.doc.value?.['props'];
  if (!Array.isArray(raw)) return [];
  const names: string[] = [];
  for (const item of raw) {
    if (!isRecord(item)) continue;
    if (item['type'] !== 'action') continue;
    const name = item['name'];
    if (typeof name === 'string') names.push(name);
  }
  return names;
}

function examplesOf(spec: SpecRow): SpecExample[] {
  const raw = spec.doc.value?.['examples'];
  if (!Array.isArray(raw)) return [];
  const out: SpecExample[] = [];
  for (const item of raw) {
    if (!isRecord(item)) continue;
    const id = item['id'];
    if (typeof id !== 'string') continue;
    const props = isRecord(item['props']) ? Object.entries(item['props']) : [];
    const grid = Array.isArray(item['grid']) ? item['grid'].filter((g): g is string => typeof g === 'string') : [];
    const schemes = Array.isArray(item['schemes'])
      ? item['schemes'].filter((s): s is string => typeof s === 'string')
      : ['light', 'dark'];
    out.push({
      id,
      props,
      surface: typeof item['surface'] === 'string' ? item['surface'] : null,
      backdrop: typeof item['backdrop'] === 'string' ? item['backdrop'] : null,
      grid,
      schemes,
      description: typeof item['description'] === 'string' ? item['description'] : null,
    });
  }
  return out;
}

/**
 * `notes.platform`, one note per spec platform key. A key that is not one of them is a problem, not a
 * note to skip: the schema rejects it too (spec/component.schema.json), and a misspelt `watchos` dropped
 * here would take its note out of the app without a word.
 */
function platformNotesOf(spec: SpecRow, problems: string[]): readonly (readonly [string, string])[] {
  const notes = spec.doc.value?.['notes'];
  if (!isRecord(notes)) return [];
  const platform = notes['platform'];
  if (!isRecord(platform)) return [];
  const out: [string, string][] = [];
  for (const [key, value] of Object.entries(platform)) {
    if (!(PLATFORMS as readonly string[]).includes(key)) {
      problems.push(`${spec.file}: notes.platform.${key} is not a spec platform key (${PLATFORMS.join(', ')})`);
    } else if (typeof value === 'string') {
      out.push([key, value]);
    }
  }
  return out;
}

function stringField(spec: SpecRow, field: string): string | null {
  const value = spec.doc.value?.[field];
  return typeof value === 'string' ? value.trim() : null;
}

/** `implemented` of the two Swift manifests, keyed by component name → platform → version. */
export function appleImplemented(reader: SourceReader, problems: string[]): Map<string, Map<string, number>> {
  const out = new Map<string, Map<string, number>>();
  for (const manifest of MANIFESTS) {
    if (manifest.stack !== 'swiftui') continue;
    if (!reader.exists(manifest.path)) {
      problems.push(`${manifest.path} is missing`);
      continue;
    }
    const parsed = parseManifest(reader.readText(manifest.path), manifest.syntax);
    for (const problem of parsed.problems) problems.push(`${manifest.path}:${problem.line} ${problem.message}`);
    for (const entry of parsed.entries) {
      const versions = out.get(entry.name) ?? new Map<string, number>();
      for (const version of entry.versions) versions.set(version.platform, version.version);
      out.set(entry.name, versions);
    }
  }
  return out;
}

export interface ComponentCatalog {
  readonly catalog: OutputFile;
  readonly bindings: OutputFile;
  /** The components this build implements on at least one Apple platform, in spec order. */
  readonly implementedNames: readonly string[];
}

function repositoryUrl(reader: SourceReader): string {
  const pkg = JSON.parse(reader.readText(TOKENS_PACKAGE)) as { repository?: { url?: string } };
  const url = pkg.repository?.url ?? '';
  return url.replace(/^git\+/, '').replace(/\.git$/, '');
}

export function renderComponentCatalog(reader: SourceReader, problems: string[]): ComponentCatalog {
  const { specs, diagnostics } = readSpecs(reader);
  for (const d of diagnostics) problems.push(`${d.file ?? '?'}: ${d.message}`);
  const implemented = appleImplemented(reader, problems);

  const lines: string[] = [
    header('spec/components, spec/patterns and the Swift implementation manifests'),
    '//',
    '// Every spec is a row, implemented or not, so the app can never silently omit one: the support level',
    '// comes from the spec, the implemented version from `DSComponentsManifest`/`DSChartsManifest`, and the',
    '// examples are the spec\'s own `examples[]` with the props as the spec writes them.',
    'import SwiftUI',
    '',
    'extension DSShowcaseCatalog {',
    `    /// Where the app links a spec, the gallery and the parity report.`,
    `    public static let repositoryURL = ${swiftString(repositoryUrl(reader))}`,
    '',
  ];

  const implementedNames: string[] = [];
  const entryLines: string[] = [];
  for (const spec of specs) {
    const versions = implemented.get(spec.name) ?? new Map<string, number>();
    const apple = APPLE_PLATFORMS.filter((p) => versions.has(p));
    const isPattern = LAYER_MANIFEST[spec.layer] === null;
    if (apple.length > 0 && !isPattern) implementedNames.push(spec.name);
    const platforms = [...spec.platforms.entries()].map(([p, s]) => `(${swiftString(p)}, .${s})`);
    const implementedPairs = apple.map((p) => `(${swiftString(p)}, ${versions.get(p) ?? 0})`);
    const examples = examplesOf(spec);
    // Every `type: action` prop of the spec. The web harness injects a no-op for each of these
    // (`web/apps/showcase/src/sections/Components.tsx`); Apple stages them through
    // `DSSpecExample.handler(_:)`, so a Card example draws the open glyph its baseline shows
    // (Card.yaml behavior 4) instead of silently staging an unpressable card.
    const actionProps = actionPropsOf(spec);
    lines.push(
      `    static let spec${spec.name}: DSComponentEntry = DSComponentEntry(`,
      `            name: ${swiftString(spec.name)},`,
      `            layer: ${swiftString(spec.layer)},`,
      `            summary: ${swiftString(stringField(spec, 'summary') ?? '')},`,
      `            since: ${optionalString(stringField(spec, 'since'))},`,
      `            specVersion: ${spec.specVersion},`,
      `            specPath: ${swiftString(spec.file)},`,
      `            isPattern: ${isPattern ? 'true' : 'false'},`,
      `            platforms: [${platforms.join(', ')}],`,
      `            implemented: [${implementedPairs.join(', ')}],`,
      `            platformNotes: [${platformNotesOf(spec, problems).map(([k, v]) => `(${swiftString(k)}, ${swiftString(v)})`).join(', ')}],`,
      '            examples: [',
    );
    for (const example of examples) {
      const props = example.props.map(([k, v]) => `(${swiftString(k)}, ${propValue(v)})`);
      lines.push(
        `                DSSpecExample(` +
          `id: ${swiftString(example.id)}, ` +
          `props: [${props.join(', ')}], ` +
          `surface: ${optionalString(example.surface)}, ` +
          `backdrop: ${optionalString(example.backdrop)}, ` +
          `grid: [${example.grid.map(swiftString).join(', ')}], ` +
          `schemes: [${example.schemes.map(swiftString).join(', ')}], ` +
          `actions: [${actionProps.map(swiftString).join(', ')}], ` +
          `summary: ${optionalString(example.description)}),`,
      );
    }
    lines.push('            ]', '    )', '');
    entryLines.push(`        spec${spec.name},`);
  }
  lines.push('    public static let components: [DSComponentEntry] = [', ...entryLines, '    ]', '}');

  const bindingLines: string[] = [
    header('the Swift implementation manifests'),
    '//',
    '// One renderer per component this build implements on Apple. A component that lands in',
    '// `DSComponentsManifest.implemented` appears here on the next generate, and `DSShowcase` then does not',
    '// compile until `DS<Name>Renderer` exists — which is how the showcase cannot go stale without saying so.',
    'import SwiftUI',
    '',
    'extension DSShowcaseRenderers {',
    '    static let generated: [String: any DSExampleRenderer] = [',
    ...implementedNames.map((name) => `        ${swiftString(name)}: DS${name}Renderer(),`),
    '    ]',
    '}',
  ];

  return {
    catalog: { path: posix.join(GENERATED_ROOT, 'DSShowcaseCatalog.swift'), contents: file(lines) },
    bindings: { path: posix.join(GENERATED_ROOT, 'DSShowcaseBindings.swift'), contents: file(bindingLines) },
    implementedNames,
  };
}

/** Both catalogues, the renderer bindings and the key-path table, as the files a build would write. */
export function renderCatalogs(reader: SourceReader): CatalogResult {
  const problems: string[] = [];
  const tokens = renderTokenCatalog(reader, problems);
  const keyPaths = renderTokenKeyPaths(reader, problems);
  const components = renderComponentCatalog(reader, problems);
  const files = [tokens, keyPaths, components.catalog, components.bindings].sort((a, b) => (a.path < b.path ? -1 : 1));
  return { files, problems };
}
