/** Writes `swift/Showcase/PrismShowcase.xcodeproj` and returns its path. */
export function writeProject(root: string): string {
  const showcase = join(root, SHOWCASE_DIR);
  if (!existsSync(join(showcase, APP_SOURCES, `${APP_NAME}App.swift`))) {
    throw new Error(`${SHOWCASE_DIR}/${APP_SOURCES} is not there: the app's sources are committed, the project is not`);
  }
  const project = join(showcase, `${APP_NAME}.xcodeproj`);
  rmSync(project, { recursive: true, force: true });
  mkdirSync(join(project, 'xcshareddata', 'xcschemes'), { recursive: true });
  writeFileSync(join(project, 'project.pbxproj'), projectFile(root, showcase), 'utf8');
  writeFileSync(join(project, 'xcshareddata', 'xcschemes', `${APP_NAME}.xcscheme`), schemeFile(`${APP_NAME}.xcodeproj`), 'utf8');
  return project;
}
