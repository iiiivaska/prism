// The Xcode project for the showcase app (docs/showcase.md).
//
// SwiftPM cannot build an app bundle, so the app needs a project. It is written per run and gitignored, for the
// same reason `fixtures/swiftui-app`'s is (ADR-0014): the only thing in it that could drift is the package
// reference, and the sources beside it are committed. One target builds for the iOS simulator, the iPhone and
// the Mac from the one shared view layer, and links the local package's `DSShowcase` product.
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

/** Repository-relative home of the app: the shell, the library sources and the generated project. */
export const SHOWCASE_DIR = 'swift/Showcase';
export const APP_NAME = 'PrismShowcase';
/** The synchronized group, relative to the project directory. */
export const APP_SOURCES = 'App/PrismShowcase';
export const BUNDLE_ID = 'com.example.prism.showcase';
/** The one product the app links; it brings DSComponents, DSCore, DSTokens and DSIcons with it. */
export const PRODUCT = 'DSShowcase';

/** 24-character object ids, stable so a regenerated project is byte-identical. */
const ID = (n: number): string => `5H0WCA5E0000${n.toString(16).toUpperCase().padStart(12, '0')}`;
const OBJ = {
  project: ID(1),
  mainGroup: ID(2),
  productsGroup: ID(3),
  target: ID(4),
  productRef: ID(5),
  sources: ID(6),
  frameworks: ID(7),
  resources: ID(8),
  projectConfigs: ID(9),
  targetConfigs: ID(10),
  projectDebug: ID(11),
  projectRelease: ID(12),
  targetDebug: ID(13),
  targetRelease: ID(14),
  syncGroup: ID(15),
  package: ID(16),
  productDependency: ID(17),
  buildFile: ID(18),
} as const;

/** A pbxproj value, quoted whenever it is not a bare identifier. */
function value(text: string): string {
  return /^[A-Za-z0-9_.]+$/.test(text) ? text : `"${text.replace(/["\\]/gu, '\\$&')}"`;
}

